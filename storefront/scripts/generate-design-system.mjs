import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const sourcePath = resolve(root, 'design-system/tokens.json');
const outputs = {
  css: resolve(root, 'src/styles/tokens.css'),
  typescript: resolve(root, 'src/design-system/tokens.generated.ts'),
  tailwind: resolve(root, 'src/styles/theme.generated.css'),
};
const check = process.argv.includes('--check');
const source = JSON.parse(await readFile(sourcePath, 'utf8'));
const layerOrder = ['primitive', 'semantic', 'component'];
const allNames = new Map();

for (const [layerIndex, layer] of layerOrder.entries()) {
  if (!source[layer] || typeof source[layer] !== 'object') throw new Error(`Missing token layer: ${layer}`);
  for (const [name, token] of Object.entries(source[layer])) {
    if (!name.startsWith('--ds-') || typeof token?.$value !== 'string') throw new Error(`Invalid ${layer} token: ${name}`);
    if (allNames.has(name)) throw new Error(`Duplicate token: ${name}`);
    allNames.set(name, layerIndex);
  }
}

for (const [layerIndex, layer] of layerOrder.entries()) {
  for (const [name, token] of Object.entries(source[layer])) {
    for (const match of token.$value.matchAll(/var\((--ds-[\w-]+)\)/g)) {
      if (!allNames.has(match[1])) throw new Error(`${name} references missing token ${match[1]}`);
      if (allNames.get(match[1]) > layerIndex) throw new Error(`${name} has backwards reference to ${match[1]}`);
    }
  }
}

const cssLines = ['/* GENERATED by scripts/generate-design-system.mjs. DO NOT EDIT. */', ':root {'];
for (const layer of layerOrder) {
  cssLines.push(`  /* ${layer.toUpperCase()} */`);
  for (const [name, token] of Object.entries(source[layer])) cssLines.push(`  ${name}: ${token.$value};`);
}
cssLines.push('}', '');

const tokenObject = Object.fromEntries(layerOrder.map((layer) => [
  layer,
  Object.fromEntries(Object.keys(source[layer]).map((name) => [name.slice(5).replaceAll('-', '_'), name])),
]));
const ts = `/* GENERATED by scripts/generate-design-system.mjs. DO NOT EDIT. */\nexport const designTokens = ${JSON.stringify(tokenObject, null, 2)} as const;\n\nexport type DesignTokenLayer = keyof typeof designTokens;\nexport type DesignTokenName = typeof designTokens[DesignTokenLayer][keyof typeof designTokens[DesignTokenLayer]];\n`;
const theme = `/* GENERATED by scripts/generate-design-system.mjs. DO NOT EDIT. */\n@theme {\n${Object.entries(source.tailwind).map(([name, value]) => `  ${name}: ${value};`).join('\n')}\n}\n`;
const rendered = { css: cssLines.join('\n'), typescript: ts, tailwind: theme };

for (const [key, path] of Object.entries(outputs)) {
  if (check) {
    const current = await readFile(path, 'utf8').catch(() => '');
    if (current !== rendered[key]) throw new Error(`Generated artifact is stale: ${path}`);
  } else {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, rendered[key]);
  }
}
console.log(check ? 'Generated design-system artifacts are current.' : 'Generated design-system artifacts updated.');
